import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { parse } from "yaml";
import { getPageExtensions } from "./static-build-config";
import { assertStaticExport } from "./static-export-check";

test("Pages setup leaves the maintained Next config intact", () => {
  const workflow = parse(fs.readFileSync(path.join(process.cwd(), ".github/workflows/deploy.yml"), "utf8"));
  const setup = workflow.jobs.build.steps.find((step: { uses?: string }) => step.uses?.startsWith("actions/configure-pages@"));
  assert.ok(setup);
  assert.equal(setup.with?.static_site_generator, undefined,
    "configure-pages must not generate next.config.js and shadow next.config.ts");
  const build = workflow.jobs.build.steps.find((step: { run?: string }) => step.run === "pnpm build");
  assert.equal(build.env.NEXT_PUBLIC_BASE_PATH, "${{ steps.pages.outputs.base_path }}");
});

function fixture(t: test.TestContext, { withdrawn = false, draft = false } = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "nzm-static-export-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const write = (file: string, value: unknown) => {
    const target = path.join(root, file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, JSON.stringify(value));
  };
  write("data/overlimit/current.json", { withdrawn, cards: [{ id: "1317114001" }] });
  for (const id of ["black-hole", "dual-star", "matrix-symbiosis", "passives"]) {
    write(`data/season-talents/s4/${id}.json`, { draft });
  }
  write(".next/required-server-files.json", { config: {
    configFileName: "next.config.ts", pageExtensions: getPageExtensions(false, root),
  } });
  return { root, write };
}

test("rejects the config generated by Pages even when the build reports success", t => {
  const { root, write } = fixture(t);
  write(".next/required-server-files.json", { config: {
    configFileName: "next.config.js", pageExtensions: ["tsx", "ts", "jsx", "js"],
  } });
  assert.throws(() => assertStaticExport(root), /next.config.js.*unexpected pageExtensions/);
});

test("published overlimit and S4 talent pages must have exported HTML", t => {
  const { root, write } = fixture(t);
  assert.throws(() => assertStaticExport(root), /missing 4 published pages.*1317114001.*dual-star/);
  write("out/overlimit/1317114001.html", "overlimit");
  write("out/guides/season-talents/s4/black-hole.html", "black-hole");
  write("out/guides/season-talents/s4/matrix-symbiosis/index.html", "matrix-symbiosis");
  // RSC directories are not HTML pages and must not hide missing exports.
  write("out/guides/season-talents/s4/dual-star/__next._full.txt", "rsc");
  assert.throws(() => assertStaticExport(root), /missing 1 published pages.*dual-star/);
  write("out/guides/season-talents/s4/dual-star.html", "dual-star");
  assert.equal(assertStaticExport(root), 4);
});

test("withdrawn catalogs and draft talent trees do not require public pages", t => {
  const { root } = fixture(t, { withdrawn: true, draft: true });
  assert.equal(assertStaticExport(root), 0);
});
